export const SettingsModel = {
  async getSection(section) {
    const rows = await query('SELECT * FROM `system_settings` WHERE `section` = ? LIMIT 1', [section])
    if (rows.length === 0) {
      if (section === 'company') return defaultCompanySettings
      return null
    }
    const raw = rows[0].settings_data
    return typeof raw === 'string' ? JSON.parse(raw) : raw
  },

  async getAll() {
    const rows = await query('SELECT * FROM `system_settings`')
    const result = { company: defaultCompanySettings }
    for (const r of rows) {
      const data = typeof r.settings_data === 'string' ? JSON.parse(r.settings_data) : r.settings_data
      result[r.section] = data
    }
    return result
  },

  async saveSection(section, data, updatedBy = 'Super Admin') {
    const jsonData = JSON.stringify(data)
    await query(`
      INSERT INTO \`system_settings\` (\`id\`, \`section\`, \`settings_data\`, \`updated_by\`)
      VALUES (?, ?, ?, ?)
      ON DUPLICATE KEY UPDATE
        \`settings_data\` = VALUES(\`settings_data\`),
        \`updated_by\` = VALUES(\`updated_by\`),
        \`updated_at\` = CURRENT_TIMESTAMP
    `, [section, section, jsonData, updatedBy])

    return this.getSection(section)
  }
}
